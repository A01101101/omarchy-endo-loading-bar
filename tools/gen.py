#!/usr/bin/env python3
"""Generate Schemes.js (used by the plugin) and docs/themes.{md,html} from schemes.json.

Run after editing schemes.json:  python3 tools/gen.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
schemes = json.loads((root / "schemes.json").read_text())
KEYS = ("tail", "mid", "head", "drift", "layer")

# ---- Schemes.js -----------------------------------------------------------
js = [".pragma library", "", "// GENERATED by tools/gen.py from schemes.json. Do not edit by hand.", ""]
js.append("var KEYS = " + json.dumps(list(KEYS)) + ";")
js.append("var SCHEMES = " + json.dumps(schemes, indent=2) + ";")
js.append(r'''
function hexToRgb(hex) {
  var h = String(hex).replace("#", "");
  if (h.length === 3) h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2];
  return [parseInt(h.substr(0, 2), 16), parseInt(h.substr(2, 2), 16), parseInt(h.substr(4, 2), 16)];
}

function rgbScheme(s) {
  var out = {};
  for (var i = 0; i < KEYS.length; i++) out[KEYS[i]] = hexToRgb(s[KEYS[i]]);
  return out;
}

function slug(name) {
  return String(name || "").trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function mix(a, b, t) {
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
}

// Parse the flat `key = "#hex"` lines of an Omarchy colors.toml.
function parseColors(text) {
  var out = {};
  var lines = String(text || "").split("\n");
  for (var i = 0; i < lines.length; i++) {
    var m = lines[i].match(/^\s*([A-Za-z_]+)\s*=\s*"(#[0-9A-Fa-f]{3,8})"/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

// Build a scheme for a theme we have no hand-made palette for (custom or new
// themes) from its colors.toml.
function deriveScheme(colors) {
  var accent = colors.accent || colors.blue || "#7aa2f7";
  var rgb = hexToRgb(accent);
  var head = colors.bright_foreground || colors.foreground || "#ffffff";
  var headRgb = mix(hexToRgb(head), rgb, 0.35);
  function toHex(c) {
    return "#" + c.map(function (v) {
      var n = Math.max(0, Math.min(255, Math.round(v))).toString(16);
      return n.length < 2 ? "0" + n : n;
    }).join("");
  }
  return {
    name: "Derived",
    mode: colors.mode || "dark",
    tail: colors.magenta || colors.muted || accent,
    mid: accent,
    head: toHex(headRgb),
    drift: colors.cyan || colors.bright_cyan || accent,
    layer: colors.bright_magenta || colors.magenta || accent
  };
}
''')
(root / "Schemes.js").write_text("\n".join(js))

# ---- docs -----------------------------------------------------------------
md = ["# Colour schemes", "",
      "One hand-picked scheme for each of the 24 default Omarchy themes. The bar switches",
      "to the matching scheme the moment you change theme, with a short crossfade.", "",
      "Roles: **tail** is the left edge, **mid** the body, **head** the glowing tip and the",
      "drifting light waves, **drift** is the colour the body slowly breathes toward, and",
      "**layer** tints the slower second wave layer.", "",
      "| Theme | Mode | Tail | Mid | Head | Drift | Layer |", "|---|---|---|---|---|---|---|"]
for slug, s in schemes.items():
    md.append(f"| {s['name']} (`{slug}`) | {s['mode']} | " + " | ".join(f"`{s[k]}`" for k in KEYS) + " |")
md += ["", "Themes that are not in this table (your own, or Aether-generated ones) get a scheme",
       "derived automatically from their `colors.toml`: accent for the body, magenta for the",
       "tail, cyan for the drift.", "",
       "Preview: open [themes.html](themes.html) in a browser.", ""]
(root / "docs" / "themes.md").write_text("\n".join(md))

rows = []
for slug, s in schemes.items():
    bg = "#f4f1ea" if s["mode"] == "light" else "#14151a"
    grad = f"linear-gradient(90deg, {s['tail']}, {s['mid']} 60%, {s['head']})"
    chips = "".join(f'<i title="{k}" style="background:{s[k]}"></i>' for k in KEYS)
    rows.append(f'<div class="row" style="background:{bg}"><div class="label" style="color:{"#222" if s["mode"]=="light" else "#ddd"}">{s["name"]}</div>'
                f'<div class="bar" style="background:{grad}"></div><div class="chips">{chips}</div></div>')
html = f"""<!doctype html><meta charset="utf-8"><title>endo-loading-bar colour schemes</title>
<style>
body{{margin:0;padding:24px;background:#0b0b0e;font:14px system-ui,sans-serif;color:#ccc}}
h1{{font-size:18px;font-weight:600}} .row{{display:flex;align-items:center;gap:16px;padding:14px 16px;margin:6px 0;border-radius:8px}}
.label{{width:150px}} .bar{{flex:1;height:2px;border-radius:1px;box-shadow:0 0 6px rgba(255,255,255,.12)}}
.chips{{display:flex;gap:4px}} .chips i{{width:14px;height:14px;border-radius:50%;display:block}}
</style><h1>endo-loading-bar: 24 colour schemes</h1>{"".join(rows)}"""
(root / "docs" / "themes.html").write_text(html)
print(f"generated Schemes.js and docs for {len(schemes)} schemes")
